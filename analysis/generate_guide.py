#!/usr/bin/env python3
"""
Step 7: generate PRESETS_GUIDE.md from the rated presets.

Input   analysis/.cache/presets.json   (rate.py)
        analysis/.cache/metrics.json   (measure.py; pairwise deltaE for near-duplicates)
Output  analysis/PRESETS_GUIDE.md

Nothing here is hand-written per preset; every line comes from presets.json.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent
PRESETS = HERE / ".cache" / "presets.json"
METRICS = HERE / ".cache" / "metrics.json"
OUT = HERE / "PRESETS_GUIDE.md"

NEAR_DUPLICATE_DELTA_E = 0.015   # mean OKLab deltaE below this: near-duplicate pair
LOOK_ORDER = ["True to life", "Warm & glowy", "Vivid & punchy", "Faded & moody",
              "Cool & cinematic", "Black & white", "Vintage"]
SCENE_LABELS = [("skin", "Skin"), ("landscape", "Landscape"), ("low_light", "Low light"),
                ("harsh_sun", "Harsh sun"), ("indoor_warm", "Indoor warm light"), ("food", "Food")]


def near_duplicates(metrics: dict) -> list[tuple[str, str, float]]:
    pairs = []
    for key, d in metrics.get("_pairwise_deltaE_ok", {}).items():
        a, b = key.split("|")
        if d < NEAR_DUPLICATE_DELTA_E:
            pairs.append((a, b, d))
    return sorted(pairs, key=lambda p: p[2])


def main() -> int:
    presets = json.loads(PRESETS.read_text())
    metrics = json.loads(METRICS.read_text())
    lines = ["# Carbon preset guide", "",
             "Generated by `analysis/generate_guide.py` from `analysis/rate.py` output. "
             "Do not edit by hand.", ""]
    for look in LOOK_ORDER:
        group = sorted((p for p in presets.values() if p["look"] == look),
                       key=lambda p: p["display_name"])
        if not group:
            continue
        lines += [f"## {look}", ""]
        for p in group:
            r, s, c = p["scene_ratings"], p["sliders"], p["copy"]
            lines += [f"### {p['display_name']}", "",
                      c["vibe"], "",
                      f"- Great for: {', '.join(c['great_for']) or 'none rated Great'}",
                      f"- Watch out: {c['watch_out']}",
                      f"- Scenes: " + "; ".join(f"{label} {r[k]}" for k, label in SCENE_LABELS),
                      f"- Muted to vivid {s['vibrance']}/5, soft to punchy {s['punch']}/5, "
                      f"cool to warm {s['warmth']}/5",
                      f"- Grain: {p['grain']}", ""]
    dups = near_duplicates(metrics)
    lines += ["## Near-duplicates", ""]
    if dups:
        for a, b, d in dups:
            lines.append(f"- {presets[a]['display_name']} and {presets[b]['display_name']} "
                         f"(mean deltaE {d:.4f})")
    else:
        lines.append("None below the threshold.")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(presets)} presets, {len(dups)} near-duplicate pairs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
